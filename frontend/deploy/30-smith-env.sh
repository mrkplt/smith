export SMITH_API_BASE_URL
export SMITH_CHAT_BASE_URL
export SMITH_OPERATOR_TOKEN
export SMITH_OPERATOR_PERMISSIONS
export SMITH_FEATURE_TASKS_ENABLED
export SMITH_FEATURE_CAPABILITY_ENABLED
export SMITH_FEATURE_CAPABILITY_ACCESS
export SMITH_SHOW_COMING_SOON_PROVIDERS

envsubst '${SMITH_API_BASE_URL} ${SMITH_CHAT_BASE_URL} ${SMITH_OPERATOR_TOKEN} ${SMITH_OPERATOR_PERMISSIONS} ${SMITH_FEATURE_TASKS_ENABLED} ${SMITH_FEATURE_CAPABILITY_ENABLED} ${SMITH_FEATURE_CAPABILITY_ACCESS} ${SMITH_SHOW_COMING_SOON_PROVIDERS}' < /opt/smith/runtime-config.template.js > /tmp/runtime-config.js
