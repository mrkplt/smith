#!/bin/sh
set -eu

: "${SMITH_API_BASE_URL:=/api}"
: "${SMITH_CHAT_BASE_URL:=/chat}"
: "${SMITH_OPERATOR_TOKEN:=}"
: "${SMITH_OPERATOR_PERMISSIONS:=}"
: "${SMITH_FEATURE_TASKS_ENABLED:=false}"
: "${SMITH_FEATURE_CAPABILITY_ENABLED:=false}"
: "${SMITH_FEATURE_CAPABILITY_ACCESS:=false}"
